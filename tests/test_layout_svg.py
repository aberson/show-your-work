"""Tests for the house SVG engine (plan Phase 2 section 2.5) written by ``render``.

Every SVG here is produced by the production caller ``cli.main`` on a tmp copy of a synthetic
fixture. The goldens in ``tests/fixtures/layout/golden/`` pin the bytes; the geometry, palette and
escaping tests are independent of them: each expected position is computed from the sidecar JSON
with the section 2.5 formulas over the geometry constants (whose values are anchored once, below).
"""

from __future__ import annotations

import copy
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any, cast

import pytest

from show_your_work import header
from show_your_work.cli import main
from show_your_work.constants import (
    EXIT_OK,
    HOUSE_BOTTOM_PAD,
    HOUSE_DASH,
    HOUSE_GUTTER,
    HOUSE_MARGIN,
    HOUSE_PALETTES,
    HOUSE_PILL_HEIGHT,
    HOUSE_PILL_WIDTH,
    HOUSE_REJOIN_DROP,
    HOUSE_REJOIN_PAD,
    HOUSE_ROW_PITCH,
    HOUSE_SIDE_DROP,
    HOUSE_SVG_MARKER,
    HOUSE_TOP,
    PALETTE_SPINE,
    RASTER_DARK,
    RASTER_LIGHT,
    RASTER_THEMES,
    SVG_NAMESPACE,
)
from tests.fakes import layout_project, snapshot

FIXTURES = Path(__file__).parent / "fixtures"
VALID = FIXTURES / "layout" / "valid"
GOLDEN = FIXTURES / "layout" / "golden"

#: The sidecar diagrams of ``layout/valid`` (``plain.mmd`` has none).
SIDECAR_IDS = ("feedback", "flow")

SVG = f"{{{SVG_NAMESPACE}}}"
PATH_STEP_RE = re.compile(r"([MHV])([-0-9.]+)(?:,([-0-9.]+))?")


def _render(target: Path) -> Path:
    assert main(["render", str(target)]) == EXIT_OK
    return target


def _sidecar(target: Path, diagram_id: str) -> dict[str, Any]:
    document: dict[str, Any] = json.loads((target / f"{diagram_id}.layout.json").read_bytes())
    return document


def _svg_root(target: Path, diagram_id: str, theme: str) -> ET.Element:
    return ET.fromstring((target / "rasters" / f"{diagram_id}-{theme}.svg").read_bytes())


def _with_sidecar(tmp_path: Path, doc: dict[str, Any], *, diagram_id: str = "flow") -> Path:
    """A tmp project holding ``valid/flow.mmd`` as ``<diagram_id>.mmd`` with ``doc`` as its sidecar.

    ``flow.layout.json`` pins that file's hash, so ``doc`` stays fresh.
    """
    target = layout_project(tmp_path / "proj")
    (target / f"{diagram_id}.mmd").write_bytes((VALID / "flow.mmd").read_bytes())
    (target / f"{diagram_id}.layout.json").write_bytes(json.dumps(doc, indent=2).encode("ascii"))
    return target


def _flow_doc() -> dict[str, Any]:
    document: dict[str, Any] = json.loads((VALID / "flow.layout.json").read_bytes())
    return copy.deepcopy(document)


def _num(value: str | None) -> float:
    assert value is not None
    return float(value)


def _node_y(node: dict[str, Any], node_index: int) -> int:
    return HOUSE_TOP + node_index * HOUSE_ROW_PITCH + (HOUSE_SIDE_DROP if node["side"] else 0)


def _lane_x(index: int) -> int:
    return HOUSE_MARGIN + index * (HOUSE_PILL_WIDTH + HOUSE_GUTTER)


def _expected_size(doc: dict[str, Any]) -> tuple[int, int]:
    lanes = doc["lanes"]
    width = 2 * HOUSE_MARGIN + len(lanes) * HOUSE_PILL_WIDTH + (len(lanes) - 1) * HOUSE_GUTTER
    bottom = max(
        _node_y(lane["nodes"][-1], len(lane["nodes"]) - 1) + HOUSE_PILL_HEIGHT for lane in lanes
    )
    if doc["rejoin"] is None:
        return width, bottom + HOUSE_BOTTOM_PAD
    return width, bottom + HOUSE_REJOIN_DROP + HOUSE_REJOIN_PAD


def _pills(root: ET.Element) -> list[ET.Element]:
    return [r for r in root.iter(f"{SVG}rect") if _num(r.get("width")) == HOUSE_PILL_WIDTH]


def _path_ends(d: str) -> tuple[tuple[float, float], tuple[float, float]]:
    """Start and end point of an absolute ``M`` / ``H`` / ``V`` path."""
    x = y = 0.0
    start: tuple[float, float] | None = None
    for command, first, second in PATH_STEP_RE.findall(d):
        if command == "M":
            x, y = float(first), float(second)
            start = (x, y)
        elif command == "H":
            x = float(first)
        else:
            y = float(first)
    assert start is not None
    return start, (x, y)


