# --- goldens and determinism ------------------------------------------------------------------


def test_render_writes_both_svgs_equal_to_the_goldens(tmp_path: Path) -> None:
    target = _render(layout_project(tmp_path / "proj", VALID))
    written = sorted(p.name for p in (target / "rasters").iterdir())
    assert written == sorted(f"{i}-{t}.svg" for i in SIDECAR_IDS for t in RASTER_THEMES)
    for name in written:
        assert (target / "rasters" / name).read_bytes() == (GOLDEN / name).read_bytes(), name
    assert (target / "README.md").read_bytes() == (GOLDEN / "README.md").read_bytes()


def test_goldens_are_lf_ascii_and_parse_as_xml() -> None:
    for path in sorted(GOLDEN.glob("*.svg")):
        raw = path.read_bytes()
        assert raw.isascii() and b"\r" not in raw and raw.endswith(b"</svg>\n"), path.name
        ET.fromstring(raw)


def test_second_render_changes_no_bytes(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    target = _render(layout_project(tmp_path / "proj", VALID))
    before = snapshot(target)
    capsys.readouterr()
    _render(target)
    out = capsys.readouterr().out
    assert "written" not in out and "deleted" not in out
    assert snapshot(target) == before


# --- geometry, independent of the goldens -----------------------------------------------------


@pytest.mark.parametrize("theme", RASTER_THEMES)
@pytest.mark.parametrize("diagram_id", SIDECAR_IDS)
def test_pill_rects_sit_on_the_lane_and_row_grid(
    diagram_id: str, theme: str, tmp_path: Path
) -> None:
    target = _render(layout_project(tmp_path / "proj", VALID))
    doc = _sidecar(target, diagram_id)
    expected = [
        (_lane_x(index), _node_y(node, node_index), float(HOUSE_PILL_HEIGHT))
        for index, lane in enumerate(doc["lanes"])
        for node_index, node in enumerate(lane["nodes"])
    ]
    pills = _pills(_svg_root(target, diagram_id, theme))
    found = [(_num(r.get("x")), _num(r.get("y")), _num(r.get("height"))) for r in pills]
    assert found == expected


def test_viewbox_follows_the_formulas_with_and_without_a_rejoin(tmp_path: Path) -> None:
    with_rejoin = _render(layout_project(tmp_path / "proj", VALID))
    no_rejoin_doc = {**_flow_doc(), "rejoin": None}
    without = _render(_with_sidecar(tmp_path / "bare", no_rejoin_doc))
    cases = [
        (with_rejoin, "flow", _sidecar(with_rejoin, "flow")),
        (with_rejoin, "feedback", _sidecar(with_rejoin, "feedback")),
        (without, "flow", no_rejoin_doc),
    ]
    sizes = set()
    for target, diagram_id, doc in cases:
        width, height = _expected_size(doc)
        sizes.add((width, height))
        for theme in RASTER_THEMES:
            root = _svg_root(target, diagram_id, theme)
            assert root.get("viewBox") == f"0 0 {width} {height}"
            assert (root.get("width"), root.get("height")) == (str(width), str(height))
    assert len(sizes) == len(cases)  # the rejoin really changes the height


@pytest.mark.parametrize("diagram_id", SIDECAR_IDS)
def test_each_theme_file_carries_only_its_own_palette(diagram_id: str, tmp_path: Path) -> None:
    target = _render(layout_project(tmp_path / "proj", VALID))
    for theme, other in ((RASTER_LIGHT, RASTER_DARK), (RASTER_DARK, RASTER_LIGHT)):
        text = (target / "rasters" / f"{diagram_id}-{theme}.svg").read_text(encoding="ascii")
        for colour in HOUSE_PALETTES[theme].values():
            assert colour in text, (theme, colour)
        for colour in HOUSE_PALETTES[other].values():
            assert colour not in text, (theme, colour)


@pytest.mark.parametrize("theme", RASTER_THEMES)
def test_side_pills_are_dashed_and_unshadowed(theme: str, tmp_path: Path) -> None:
    target = _render(layout_project(tmp_path / "proj", VALID))
    doc = _sidecar(target, "flow")
    sides = {
        (_lane_x(index), _node_y(node, node_index))
        for index, lane in enumerate(doc["lanes"])
        for node_index, node in enumerate(lane["nodes"])
        if node["side"]
    }
    assert sides  # the fixture has a side node
    for pill in _pills(_svg_root(target, "flow", theme)):
        if (_num(pill.get("x")), _num(pill.get("y"))) in sides:
            assert pill.get("stroke-dasharray") == HOUSE_DASH
            assert pill.get("filter") is None
        else:
            assert pill.get("stroke-dasharray") is None
            assert pill.get("filter") is not None


@pytest.mark.parametrize("theme", RASTER_THEMES)
@pytest.mark.parametrize("diagram_id", SIDECAR_IDS)
def test_spine_runs_from_out_right_centre_to_in_left_centre(
    diagram_id: str, theme: str, tmp_path: Path
) -> None:
    target = _render(layout_project(tmp_path / "proj", VALID))
    lanes = _sidecar(target, diagram_id)["lanes"]
    expected = []
    for index, (left, right) in enumerate(zip(lanes, lanes[1:], strict=False)):
        out_y = _node_y(left["nodes"][left["out"]], left["out"]) + HOUSE_PILL_HEIGHT / 2
        in_y = _node_y(right["nodes"][right["in"]], right["in"]) + HOUSE_PILL_HEIGHT / 2
        expected.append(((_lane_x(index) + HOUSE_PILL_WIDTH, out_y), (_lane_x(index + 1), in_y)))
    spine = HOUSE_PALETTES[theme][PALETTE_SPINE]
    root = _svg_root(target, diagram_id, theme)
    paths = [p for p in root.iter(f"{SVG}path") if p.get("stroke") == spine]
    assert [_path_ends(p.get("d") or "") for p in paths] == expected


# --- structure and escaping -------------------------------------------------------------------


def test_marker_comment_is_the_first_child_of_the_root(tmp_path: Path) -> None:
    target = _render(layout_project(tmp_path / "proj", VALID))
    raw = (target / "rasters" / "flow-light.svg").read_text(encoding="ascii")
    parser = ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))
    root = ET.fromstring(raw, parser=parser)
    assert root.tag == f"{SVG}svg" and root.get("role") == "img"
    first = root[0]
    assert cast(object, first.tag) is ET.Comment  # the TreeBuilder comment factory
    assert f"<!--{first.text}-->" == HOUSE_SVG_MARKER
    assert root[1].tag == f"{SVG}defs"


def test_sidecar_strings_are_escaped_in_the_svg_and_the_readme(tmp_path: Path) -> None:
    doc = _flow_doc()
    doc["alt"] = 'Plan <&" build, with a dashed return.'
    doc["lanes"][0]["nodes"][0]["name"] = 'Take <&" order'
    target = _render(_with_sidecar(tmp_path, doc))
    for theme in RASTER_THEMES:
        raw = (target / "rasters" / f"flow-{theme}.svg").read_text(encoding="ascii")
        assert 'aria-label="Plan &lt;&amp;&quot; build, with a dashed return."' in raw
        assert ">Take &lt;&amp;&quot; order</text>" in raw
        assert '<&"' not in raw
        root = ET.fromstring(raw)  # escaped text round-trips through a real XML parser
        assert root.get("aria-label") == doc["alt"]
        assert doc["lanes"][0]["nodes"][0]["name"] in [t.text for t in root.iter(f"{SVG}text")]
    readme = (target / "README.md").read_text(encoding="ascii")
    assert '<img alt="Plan &lt;&amp;&quot; build, with a dashed return."' in readme


def test_double_hyphen_id_svgs_parse_as_xml(tmp_path: Path) -> None:
    doc = _flow_doc()
    target = _render(_with_sidecar(tmp_path, doc, diagram_id="a--b"))
    for theme in RASTER_THEMES:
        raw = (target / "rasters" / f"a--b-{theme}.svg").read_bytes()
        assert ET.fromstring(raw).tag == f"{SVG}svg"
    assert header.sha256_lf((target / "a--b.mmd").read_bytes()) == doc["source_sha256"]
